#!/usr/bin/env node
// Generates sdk/core/src/profiles.generated.{hpp,cpp} from profiles/*.json.
// osls-core is dependency-free, so the profile order tables are compiled in
// rather than parsed at runtime. Deterministic (sorted keys) for a stable diff.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const profilesDir = join(here, "../../../profiles");
const outDir = join(here, "../src");

const files = readdirSync(profilesDir).filter((f) => f.endsWith(".json")).sort();
const norm = [];
for (const f of files) {
  const p = JSON.parse(readFileSync(join(profilesDir, f), "utf8"));
  if (p.status !== "normative") continue;
  const layouts = p.layouts ?? {};
  const entries = Object.keys(layouts).sort().map((lid) => {
    const order = layouts[lid].order.map((e) => (typeof e === "string" ? e : e.sp));
    return { lid, order };
  });
  norm.push({ format: p.format, entries });
}
norm.sort((a, b) => (a.format < b.format ? -1 : 1));

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
const vec = (arr) => `{${arr.map((s) => `"${esc(s)}"`).join(", ")}}`;

const hpp = `// GENERATED by sdk/core/scripts/gen-profiles.mjs from profiles/*.json. DO NOT EDIT.
#pragma once
#include <string>
#include <vector>
namespace osls::profiles {
// Channel order (BS.2051 sp labels) a delivery format defines for a layout id, or nullptr.
const std::vector<std::string>* orderForLayout(const std::string& format, const std::string& layoutId);
// Normative formats (sorted) that define an order for this layout id.
std::vector<std::string> formatsForLayout(const std::string& layoutId);
}  // namespace osls::profiles
`;

let body = "";
for (const { format, entries } of norm) {
  body += `    {"${esc(format)}", {\n`;
  for (const { lid, order } of entries) body += `      {"${esc(lid)}", ${vec(order)}},\n`;
  body += `    }},\n`;
}

const cpp = `// GENERATED by sdk/core/scripts/gen-profiles.mjs from profiles/*.json. DO NOT EDIT.
#include "profiles.generated.hpp"
#include <map>
namespace osls::profiles {
namespace {
const std::map<std::string, std::map<std::string, std::vector<std::string>>> kProfiles = {
${body}};
}  // namespace
const std::vector<std::string>* orderForLayout(const std::string& format, const std::string& layoutId) {
    auto f = kProfiles.find(format);
    if (f == kProfiles.end()) return nullptr;
    auto l = f->second.find(layoutId);
    if (l == f->second.end()) return nullptr;
    return &l->second;
}
std::vector<std::string> formatsForLayout(const std::string& layoutId) {
    std::vector<std::string> out;
    for (const auto& kv : kProfiles)
        if (kv.second.count(layoutId)) out.push_back(kv.first);  // std::map keys already sorted
    return out;
}
}  // namespace osls::profiles
`;

writeFileSync(join(outDir, "profiles.generated.hpp"), hpp);
writeFileSync(join(outDir, "profiles.generated.cpp"), cpp);
console.error(`generated profiles.generated.{hpp,cpp}: ${norm.length} formats`);
