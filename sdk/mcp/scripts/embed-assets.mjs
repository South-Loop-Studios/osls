// Generates src/assets.generated.ts embedding the 14 blessed layouts, the JSON Schema,
// and docs/SPEC.md — so the published package is self-contained. Run via `npm run embed`
// (part of build + test). Re-run when layouts/schema/spec change.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../..");                 // sdk/mcp/scripts -> osls
const layoutsDir = join(repo, "layouts");

const presets = {};
for (const f of readdirSync(layoutsDir).filter((f) => f.endsWith(".osls"))) {
  presets[f.replace(/\.osls$/, "")] = readFileSync(join(layoutsDir, f), "utf8");
}
const schema = JSON.parse(readFileSync(join(repo, "schema/osls.schema.json"), "utf8"));
const specMd = readFileSync(join(repo, "docs/SPEC.md"), "utf8");

const out =
  "// GENERATED by scripts/embed-assets.mjs — do not edit. Run `npm run embed`.\n" +
  `export const PRESETS: Record<string, string> = ${JSON.stringify(presets, null, 2)};\n` +
  `export const SCHEMA: object = ${JSON.stringify(schema)};\n` +
  `export const SPEC_MD: string = ${JSON.stringify(specMd)};\n`;
writeFileSync(join(here, "../src/assets.generated.ts"), out);
console.log(`embedded ${Object.keys(presets).length} presets + schema + spec`);
