#!/usr/bin/env node
// GENERATOR: bundles layouts/*.osls into @orbitspatial/osls-core as PRESETS so consumers get the
// blessed layout set from the package (no repo glob). Deterministic (sorted keys).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const layoutsDir = join(here, "../../../layouts");

const files = readdirSync(layoutsDir).filter((f) => f.endsWith(".osls")).sort();
const entries = files.map((f) => {
  const id = f.replace(/\.osls$/, "");
  return `  ${JSON.stringify(id)}: ${JSON.stringify(readFileSync(join(layoutsDir, f), "utf8"))},`;
});

const out =
  `// GENERATED by scripts/embed-presets.mjs from layouts/*.osls. DO NOT EDIT.\n` +
  `// The blessed layout set, bundled so @orbitspatial/osls-core consumers (designer, tools) get\n` +
  `// the presets from the package rather than globbing the repo's layouts/ dir.\n` +
  `export const PRESETS: Record<string, string> = {\n${entries.join("\n")}\n};\n`;

writeFileSync(join(here, "../src/presets.generated.ts"), out);
console.error(`embedded ${files.length} presets`);
